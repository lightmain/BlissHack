import { readFile, writeFile } from "node:fs/promises";
import { join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { PNG } from "pngjs";
import { SaxesParser } from "saxes";

const frontendRoot = resolve(import.meta.dirname, "..", "..");
const sourcePath = join(frontendRoot, "public", "favicon.svg");
const assetRoot = join(frontendRoot, "electron", "assets");
const pngPath = join(assetRoot, "icon.png");
const icoPath = join(assetRoot, "icon.ico");
const icnsPath = join(assetRoot, "icon.icns");
const isMainModule = process.argv[1]
  && resolve(process.argv[1]) === fileURLToPath(import.meta.url);
const arguments_ = isMainModule ? process.argv.slice(2) : [];
const checkOnly = arguments_.includes("--check");
const unsupportedArguments = arguments_.filter(
  (argument) => argument !== "--check",
);

if (unsupportedArguments.length > 0) {
  throw new Error(`Unsupported icon generator arguments: ${
    unsupportedArguments.join(", ")
  }`);
}

const ICNS_IMAGES = [
  ["ic04", 16],
  ["ic05", 32],
  ["ic07", 128],
  ["ic08", 256],
  ["ic09", 512],
  ["ic10", 1024],
];
const ICO_SIZES = [16, 32, 48, 256];

/**
 * Generate all platform icon buffers from the authoritative SVG.
 * @returns {Promise<Map<string, Buffer>>} Output paths and generated bytes.
 */
async function generateIcons() {
  const source = await readFile(sourcePath, "utf8");
  const design = parseIconSvg(source);
  const pngs = new Map(
    [...new Set([
      1024,
      ...ICO_SIZES,
      ...ICNS_IMAGES.map(([, size]) => size),
    ])].map((size) => [size, renderPng(design, size)]),
  );

  return new Map([
    [pngPath, pngs.get(1024)],
    [icoPath, createIco(ICO_SIZES.map((size) => [size, pngs.get(size)]))],
    [
      icnsPath,
      createIcns(ICNS_IMAGES.map(([type, size]) => [
        type,
        pngs.get(size),
      ])),
    ],
  ]);
}

/**
 * Parse the deliberately small SVG subset used by the pixel icon.
 * @param {string} source Authoritative SVG text.
 * @returns {{
 *   width: number,
 *   height: number,
 *   background: { color: number[], rects: object[] },
 *   glyph: { color: number[], rects: object[] },
 * }} Validated raster design.
 */
function parseIconSvg(source) {
  let root;
  let background;
  let glyph;
  let title;
  let titleText = "";
  const elementStack = [];
  const parser = new SaxesParser();

  parser.on("opentag", (node) => {
    const name = node.name;
    const attributes = Object.fromEntries(
      Object.entries(node.attributes).map(([key, value]) => [
        key,
        typeof value === "string" ? value : value.value,
      ]),
    );
    const parent = elementStack.at(-1);

    if (name === "svg") {
      if (root || parent) {
        throw new Error("The icon SVG must contain one root svg element");
      }
      assertAllowedAttributes(
        attributes,
        new Set([
          "aria-labelledby",
          "role",
          "shape-rendering",
          "viewBox",
          "xmlns",
        ]),
        "svg root",
      );
      root = attributes;
    } else if (name === "title") {
      if (parent !== "svg" || title) {
        throw new Error("The icon SVG must contain one root title");
      }
      assertAllowedAttributes(attributes, new Set(["id"]), "title");
      title = attributes;
    } else if (name === "rect") {
      if (parent !== "svg" || background) {
        throw new Error("The icon SVG must contain one background rect");
      }
      assertAllowedAttributes(
        attributes,
        new Set(["fill", "height", "width", "x", "y"]),
        "background",
      );
      background = attributes;
    } else if (name === "path") {
      if (
        parent !== "svg"
        || glyph
        || attributes["data-glyph"] !== "@"
      ) {
        throw new Error("The icon SVG must contain one root @ path");
      }
      assertAllowedAttributes(
        attributes,
        new Set(["d", "data-glyph", "fill"]),
        "@ glyph",
      );
      glyph = attributes;
    } else {
      throw new Error(`The icon SVG does not support <${name}>`);
    }
    elementStack.push(name);
  });
  parser.on("text", (text) => {
    if (elementStack.at(-1) === "title") {
      titleText += text;
    } else if (text.trim()) {
      throw new Error("The icon SVG only allows text inside its title");
    }
  });
  parser.on("closetag", () => {
    elementStack.pop();
  });
  parser.write(source).close();

  const viewBox = root?.viewBox?.trim().split(/[\s,]+/).map(Number);
  if (
    !viewBox
    || viewBox.length !== 4
    || viewBox.some((value) => !Number.isSafeInteger(value))
    || viewBox[0] !== 0
    || viewBox[1] !== 0
    || viewBox[2] <= 0
    || viewBox[2] !== viewBox[3]
  ) {
    throw new Error("The icon SVG needs a positive integer square viewBox");
  }
  if (
    root.xmlns !== "http://www.w3.org/2000/svg"
    || root.role !== "img"
    || root["shape-rendering"] !== "crispEdges"
    || !title?.id
    || !root["aria-labelledby"]?.split(/\s+/).includes(title.id)
    || !/blisshack/i.test(titleText)
    || !titleText.includes("@")
  ) {
    throw new Error("The icon SVG accessibility metadata is incomplete");
  }
  const [x, y, width, height] = [
    numberAttribute(background, "x", 0),
    numberAttribute(background, "y", 0),
    numberAttribute(background, "width"),
    numberAttribute(background, "height"),
  ];
  if (x !== 0 || y !== 0 || width !== viewBox[2] || height !== viewBox[3]) {
    throw new Error("The icon SVG background must cover the viewBox");
  }
  if (!glyph?.d) throw new Error("The icon SVG is missing its @ path");

  return {
    width: viewBox[2],
    height: viewBox[3],
    background: {
      color: parseColor(background.fill, "background"),
      rects: [{ x, y, width, height }],
    },
    glyph: {
      color: parseColor(glyph.fill, "@ glyph"),
      rects: parsePixelPath(glyph.d),
    },
  };
}

/**
 * Reject SVG attributes that the rasterizer does not interpret.
 * @param {object} attributes Parsed SVG attributes.
 * @param {Set<string>} allowed Supported attribute names.
 * @param {string} label Human-readable element label.
 * @returns {void}
 */
function assertAllowedAttributes(attributes, allowed, label) {
  const unsupported = Object.keys(attributes).filter(
    (attribute) => !allowed.has(attribute),
  );
  if (unsupported.length > 0) {
    throw new Error(
      `The icon SVG ${label} has unsupported attributes: ${
        unsupported.join(", ")
      }`,
    );
  }
}

/**
 * Read one finite integer SVG attribute.
 * @param {object | undefined} attributes Parsed SVG attributes.
 * @param {string} name Attribute name.
 * @param {number | undefined} defaultValue Value used when omitted.
 * @returns {number} Parsed integer.
 */
function numberAttribute(attributes, name, defaultValue) {
  const rawValue = attributes?.[name];
  if (rawValue === undefined && defaultValue !== undefined) return defaultValue;
  const value = Number(rawValue);
  if (!Number.isSafeInteger(value)) {
    throw new Error(`The icon SVG has an invalid ${name} attribute`);
  }
  return value;
}

/**
 * Parse a six-digit SVG color into RGBA bytes.
 * @param {string | undefined} value SVG fill value.
 * @param {string} label Human-readable element label.
 * @returns {number[]} RGBA color tuple.
 */
function parseColor(value, label) {
  const match = /^#([\da-f]{2})([\da-f]{2})([\da-f]{2})$/i.exec(value ?? "");
  if (!match) throw new Error(`The ${label} needs a solid #RRGGBB fill`);
  return [
    Number.parseInt(match[1], 16),
    Number.parseInt(match[2], 16),
    Number.parseInt(match[3], 16),
    255,
  ];
}

/**
 * Convert the icon's rectangle-only path into raster rectangles.
 * @param {string} pathData SVG path commands.
 * @returns {{ x: number, y: number, width: number, height: number }[]} Rects.
 */
function parsePixelPath(pathData) {
  const tokenPattern = /[MHVZmhvz]|-?(?:\d+(?:\.\d*)?|\.\d+)/g;
  const tokens = pathData.match(tokenPattern) ?? [];
  const leftovers = pathData
    .replace(tokenPattern, "")
    .replace(/[\s,]+/g, "");
  if (leftovers || tokens.length === 0) {
    throw new Error("The @ path contains unsupported SVG commands");
  }

  const rects = [];
  let index = 0;
  let current;
  let points;
  while (index < tokens.length) {
    const command = tokens[index++];
    if (command === "M") {
      if (points) throw new Error("The @ path has an unclosed subpath");
      current = {
        x: pathNumber(tokens[index++]),
        y: pathNumber(tokens[index++]),
      };
      points = [{ ...current }];
      continue;
    }
    if (!current || !points) {
      throw new Error("The @ path must begin each rectangle with M");
    }
    if (command === "h" || command === "H") {
      const value = pathNumber(tokens[index++]);
      current = {
        ...current,
        x: command === "h" ? current.x + value : value,
      };
      points.push({ ...current });
      continue;
    }
    if (command === "v" || command === "V") {
      const value = pathNumber(tokens[index++]);
      current = {
        ...current,
        y: command === "v" ? current.y + value : value,
      };
      points.push({ ...current });
      continue;
    }
    if (command === "z" || command === "Z") {
      rects.push(pointsToRectangle(points));
      current = undefined;
      points = undefined;
      continue;
    }
    throw new Error(`The @ path does not support ${command}`);
  }
  if (points || rects.length === 0) {
    throw new Error("The @ path must contain closed pixel rectangles");
  }
  return rects;
}

/**
 * Parse one path coordinate.
 * @param {string | undefined} token Numeric path token.
 * @returns {number} Safe integer coordinate.
 */
function pathNumber(token) {
  const value = Number(token);
  if (!Number.isSafeInteger(value)) {
    throw new Error("The @ path must use integer pixel coordinates");
  }
  return value;
}

/**
 * Validate one closed four-corner subpath as an axis-aligned rectangle.
 * @param {{ x: number, y: number }[]} points Path corners before close.
 * @returns {{ x: number, y: number, width: number, height: number }} Rectangle.
 */
function pointsToRectangle(points) {
  if (points.length !== 4) {
    throw new Error("Each @ path subpath must describe one rectangle");
  }
  const xs = [...new Set(points.map(({ x }) => x))].sort((a, b) => a - b);
  const ys = [...new Set(points.map(({ y }) => y))].sort((a, b) => a - b);
  const expectedCorners = new Set([
    `${xs[0]},${ys[0]}`,
    `${xs[0]},${ys[1]}`,
    `${xs[1]},${ys[0]}`,
    `${xs[1]},${ys[1]}`,
  ]);
  if (
    xs.length !== 2
    || ys.length !== 2
    || points.some(({ x, y }) => !expectedCorners.has(`${x},${y}`))
  ) {
    throw new Error("Each @ path subpath must be an axis-aligned rectangle");
  }
  return {
    x: xs[0],
    y: ys[0],
    width: xs[1] - xs[0],
    height: ys[1] - ys[0],
  };
}

/**
 * Rasterize the pixel design at an integer scale.
 * @param {ReturnType<typeof parseIconSvg>} design Parsed SVG design.
 * @param {number} size Square PNG size.
 * @returns {Buffer} Encoded RGBA PNG.
 */
function renderPng(design, size) {
  if (
    !Number.isSafeInteger(size)
    || size <= 0
    || size % design.width !== 0
    || size % design.height !== 0
  ) {
    throw new Error(`Icon size ${size} is not an integer design scale`);
  }
  const png = new PNG({ width: size, height: size });
  const scale = size / design.width;
  for (const layer of [design.background, design.glyph]) {
    for (const rect of layer.rects) {
      paintRectangle(png, rect, layer.color, scale);
    }
  }
  return PNG.sync.write(png, {
    colorType: 6,
    inputColorType: 6,
    inputHasAlpha: true,
    deflateLevel: 9,
    deflateStrategy: 3,
    filterType: 4,
  });
}

/**
 * Paint one scaled source rectangle into an RGBA PNG.
 * @param {PNG} png Target image.
 * @param {{ x: number, y: number, width: number, height: number }} rect Source rect.
 * @param {number[]} color RGBA color tuple.
 * @param {number} scale Integer source-to-output scale.
 * @returns {void}
 */
function paintRectangle(png, rect, color, scale) {
  const startX = rect.x * scale;
  const endX = (rect.x + rect.width) * scale;
  const startY = rect.y * scale;
  const endY = (rect.y + rect.height) * scale;
  if (
    startX < 0
    || startY < 0
    || endX > png.width
    || endY > png.height
  ) {
    throw new Error("The icon SVG draws outside its viewBox");
  }
  for (let y = startY; y < endY; y += 1) {
    for (let x = startX; x < endX; x += 1) {
      const offset = (y * png.width + x) * 4;
      png.data.set(color, offset);
    }
  }
}

/**
 * Wrap PNG frames in a Windows ICO directory.
 * @param {[number, Buffer][]} images Sizes and PNG bytes.
 * @returns {Buffer} ICO bytes.
 */
function createIco(images) {
  const directorySize = 6 + images.length * 16;
  const header = Buffer.alloc(directorySize);
  header.writeUInt16LE(0, 0);
  header.writeUInt16LE(1, 2);
  header.writeUInt16LE(images.length, 4);
  let imageOffset = directorySize;
  for (const [index, [size, bytes]] of images.entries()) {
    const entryOffset = 6 + index * 16;
    header[entryOffset] = size === 256 ? 0 : size;
    header[entryOffset + 1] = size === 256 ? 0 : size;
    header[entryOffset + 2] = 0;
    header[entryOffset + 3] = 0;
    header.writeUInt16LE(1, entryOffset + 4);
    header.writeUInt16LE(32, entryOffset + 6);
    header.writeUInt32LE(bytes.length, entryOffset + 8);
    header.writeUInt32LE(imageOffset, entryOffset + 12);
    imageOffset += bytes.length;
  }
  return Buffer.concat([header, ...images.map(([, bytes]) => bytes)]);
}

/**
 * Wrap typed PNG chunks in a macOS ICNS container.
 * @param {[string, Buffer][]} images Four-character types and PNG bytes.
 * @returns {Buffer} ICNS bytes.
 */
function createIcns(images) {
  const chunks = images.map(([type, bytes]) => {
    const chunk = Buffer.alloc(8 + bytes.length);
    chunk.write(type, 0, 4, "ascii");
    chunk.writeUInt32BE(chunk.length, 4);
    bytes.copy(chunk, 8);
    return chunk;
  });
  const header = Buffer.alloc(8);
  header.write("icns", 0, 4, "ascii");
  header.writeUInt32BE(
    header.length + chunks.reduce((sum, chunk) => sum + chunk.length, 0),
    4,
  );
  return Buffer.concat([header, ...chunks]);
}

/**
 * Write generated files or verify that checked-in outputs are current.
 * @param {Map<string, Buffer>} outputs Output paths and expected bytes.
 * @returns {Promise<void>}
 */
async function applyOutputs(outputs) {
  if (!checkOnly) {
    await Promise.all(
      [...outputs].map(([path, bytes]) => writeFile(path, bytes)),
    );
    return;
  }
  const stale = [];
  for (const [path, expected] of outputs) {
    let actual;
    try {
      actual = await readFile(path);
    } catch {
      stale.push(path);
      continue;
    }
    if (!actual.equals(expected)) stale.push(path);
  }
  if (stale.length > 0) {
    throw new Error(
      `Generated icon assets are stale: ${
        stale.map((path) => path.slice(frontendRoot.length + 1)).join(", ")
      }`,
    );
  }
}

if (isMainModule) {
  await applyOutputs(await generateIcons());
}

export { parseIconSvg };
