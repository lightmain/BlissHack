/**
 * Convert an operating-system path to a repository-relative POSIX path.
 * @param {string} path path relative to a repository root.
 * @returns {string} normalized repository-relative path.
 */
function normalizePath(path) {
  return path.split(sep).join("/");
}

/**
 * Return whether a repository path belongs to maintained project knowledge.
 * @param {string} path repository-relative path.
 * @returns {boolean} true when health checks should inspect the file.
 */
function isMaintainedPath(path) {
  if ([
    "README.md",
    "README-cn.md",
    "AGENTS.md",
    "AGENTS-cn.md",
  ].includes(path)) {
    return true;
  }
  if (path.startsWith("doc/BlissHack/prototypes/")) return false;
  if (path.startsWith("doc/BlissHack/")) {
    return /\.(?:json|md)$/i.test(path);
  }
  if (path.startsWith("scripts/docs/")) {
    return /\.(?:json|md|mjs)$/i.test(path);
  }
  return path.startsWith(".github/workflows/") && /\.ya?ml$/i.test(path);
}

/**
 * Convert one BlissHack-rooted documentation path to a status-page link.
 * @param {string} path repository-relative documentation path.
 * @returns {string} link relative to doc/BlissHack/current/status.md.
 */
function statusRelativePath(path) {
  return `../${path.replace(/^doc\/BlissHack\//, "")}`;
}

/**
 * Convert one release-manifest path to a release-index link.
 * @param {string} path repository-relative documentation path.
 * @returns {string} link relative to doc/BlissHack/releases/index.md.
 */
function releaseIndexRelativePath(path) {
  return `./${path.replace(/^doc\/BlissHack\/releases\//, "")}`;
}

/**
 * Generate the current status page from VERSION and the release manifest.
 * @param {{version: string, manifest: object}} input generation input.
 * @returns {string} complete generated Markdown.
 */
export function generateCurrentStatus({ version, manifest }) {
  const release = manifest?.releases?.find((entry) =>
    entry.version === version
  );
  if (!release) {
    throw new Error(`Release manifest has no entry for ${version}`);
  }
  const lines = [
    "# BlissHack 当前项目状态",
    "",
    "<!-- Generated by scripts/docs/documentation-health.mjs. -->",
    "> 此文件由 `VERSION` 和 `releases/manifest.json` 生成，不要手工修改。",
    "",
    `- **当前版本**：\`${version}\``,
    `- **发布状态**：${release.status ?? "unknown"}`,
  ];
  if (release.releasedOn) {
    lines.push(`- **验收日期**：${release.releasedOn}`);
  }
  lines.push(
    `- **版本范围**：${release.summary ?? "未提供摘要"}`,
    `- **版本 plan**：[查看版本 plan](${statusRelativePath(release.plan)})`,
  );
  if (release.acceptance) {
    lines.push(
      `- **发布验收**：[查看验收记录](${
        statusRelativePath(release.acceptance)
      })`,
    );
  }
  lines.push(
    "",
    "当前系统边界见[当前架构](architecture.md)。历史版本默认不属于当前实现规范。",
    "",
  );
  return lines.join("\n");
}

/**
 * Generate the human-readable release archive index.
 * @param {{currentVersion: string, releases: object[]}} manifest release data.
 * @returns {string} complete generated Markdown.
 */
export function generateReleaseIndex(manifest) {
  const lines = [
    "# BlissHack 发布归档",
    "",
    "<!-- Generated by scripts/docs/documentation-health.mjs. -->",
    "> 此文件由 `manifest.json` 生成，不要手工修改。归档记录不是当前实现规范。",
    "",
    "| 版本 | 状态 | 摘要 | 记录 |",
    "| --- | --- | --- | --- |",
  ];
  for (const release of manifest.releases ?? []) {
    const current = release.version === manifest.currentVersion
      ? "（当前）"
      : "";
    const plan = `[计划](${releaseIndexRelativePath(release.plan)})`;
    const acceptance = release.acceptance
      ? ` · [验收](${releaseIndexRelativePath(release.acceptance)})`
      : "";
    lines.push(
      `| ${release.version}${current} | ${release.status ?? "unknown"} | ${
        release.summary ?? ""
      } | ${plan}${acceptance} |`,
    );
  }
  lines.push(
    "",
    "阶段设计和发布证据位于各版本目录。调查历史时从对应版本计划开始。",
    "",
  );
  return lines.join("\n");
}

/**
 * Remove fenced code blocks before scanning prose for Markdown links.
 * @param {string} source complete Markdown source.
 * @returns {string} source with fenced block contents removed.
 */
function withoutFencedCode(source) {
  return source.replace(/^(```|~~~)[^\n]*\n[\s\S]*?^\1\s*$/gm, "");
}

/**
 * Remove inline code spans before interpreting Markdown link syntax.
 * @param {string} source Markdown source without fenced code blocks.
 * @returns {string} prose with inline code spans removed.
 */
function withoutInlineCode(source) {
  return source.replace(/(`+)([\s\S]*?)\1/g, "");
}

/**
 * Normalize one Markdown reference label according to CommonMark matching.
 * @param {string} label raw reference label.
 * @returns {string} case-insensitive, whitespace-collapsed label.
 */
function normalizeReferenceLabel(label) {
  return label.trim().replace(/\s+/g, " ").toLowerCase();
}

/**
 * Return local targets and unresolved reference labels from Markdown prose.
 * @param {string} source complete Markdown source.
 * @returns {{targets: string[], undefinedReferences: string[]}} link data.
 */
function markdownLinkData(source) {
  const prose = withoutInlineCode(withoutFencedCode(source));
  const targets = [];
  const definitions = new Map();
  const definitionPattern =
    /^\s{0,3}\[([^\]]+)\]:\s*(?:<([^>]+)>|([^\s]+))/gm;
  for (const match of prose.matchAll(definitionPattern)) {
    const label = normalizeReferenceLabel(match[1]);
    const target = match[2] ?? match[3];
    definitions.set(label, target);
    targets.push(target);
  }

  const inlinePattern = /!?\[[^\]]*]\(\s*(?:<([^>]+)>|([^\s)]+))/g;
  for (const match of prose.matchAll(inlinePattern)) {
    targets.push(match[1] ?? match[2]);
  }

  const htmlPattern =
    /\b(?:href|src)\s*=\s*(?:"([^"]+)"|'([^']+)'|([^\s"'=<>`]+))/gi;
  for (const match of prose.matchAll(htmlPattern)) {
    targets.push(match[1] ?? match[2] ?? match[3]);
  }

  const undefinedReferences = [];
  const referencePattern = /!?\[([^\]]+)]\[([^\]]*)]/g;
  for (const match of prose.matchAll(referencePattern)) {
    const label = normalizeReferenceLabel(match[2] || match[1]);
    const target = definitions.get(label);
    if (target) {
      targets.push(target);
    } else {
      undefinedReferences.push(label);
    }
  }
  return { targets: targets.filter(Boolean), undefinedReferences };
}

/**
 * Decode a percent-encoded URL component without making validation throw.
 * @param {string} value raw path or fragment.
 * @returns {string} decoded value when valid, otherwise the original value.
 */
function decodeUrlComponent(value) {
  try {
    return decodeURIComponent(value);
  } catch {
    return value;
  }
}

/**
 * Resolve one Markdown target to a repository-relative path and fragment.
 * @param {string} sourcePath repository-relative source document.
 * @param {string} target raw Markdown target.
 * @returns {{path: string, fragment: string}|null} local target data.
 */
function resolveMarkdownTarget(sourcePath, target) {
  if (
    !target
    || target.startsWith("/")
    || /^[a-z][a-z0-9+.-]*:/i.test(target)
  ) {
    return null;
  }
  const hashIndex = target.indexOf("#");
  const rawPath = (hashIndex >= 0 ? target.slice(0, hashIndex) : target)
    .split("?", 1)[0];
  const rawFragment = hashIndex >= 0 ? target.slice(hashIndex + 1) : "";
  const path = rawPath
    ? normalizePath(
      normalize(join(dirname(sourcePath), decodeUrlComponent(rawPath))),
    )
    : sourcePath;
  return {
    path,
    fragment: decodeUrlComponent(rawFragment).toLowerCase(),
  };
}

/**
 * Convert one Markdown heading to the anchor form used by GitHub Markdown.
 * @param {string} heading raw heading text.
 * @returns {string} normalized anchor slug.
 */
function githubHeadingSlug(heading) {
  return heading
    .replace(/<[^>]*>/g, "")
    .replace(/!\[([^\]]*)]\([^)]*\)/g, "$1")
    .replace(/\[([^\]]+)]\([^)]*\)/g, "$1")
    .replace(/[`*_~]/g, "")
    .trim()
    .toLowerCase()
    .replace(/[^\p{L}\p{N}\s_-]/gu, "")
    .replace(/\s+/g, "-");
}

/**
 * Return heading and explicit HTML anchors declared by one Markdown file.
 * @param {string} source complete Markdown source.
 * @returns {Set<string>} normalized anchor names.
 */
function markdownAnchors(source) {
  const prose = withoutFencedCode(source);
  const anchors = new Set();
  const slugCounts = new Map();
  const headingPattern = /^\s{0,3}#{1,6}\s+(.+?)\s*#*\s*$/gm;
  for (const match of prose.matchAll(headingPattern)) {
    const base = githubHeadingSlug(match[1]);
    const count = slugCounts.get(base) ?? 0;
    anchors.add(count === 0 ? base : `${base}-${count}`);
    slugCounts.set(base, count + 1);
  }
  const setextPattern = /^([^\n]+)\n\s{0,3}(?:=+|-+)\s*$/gm;
  for (const match of prose.matchAll(setextPattern)) {
    const base = githubHeadingSlug(match[1]);
    const count = slugCounts.get(base) ?? 0;
    anchors.add(count === 0 ? base : `${base}-${count}`);
    slugCounts.set(base, count + 1);
  }
  const explicitPattern = /\b(?:id|name)\s*=\s*["']([^"']+)["']/gi;
  for (const match of prose.matchAll(explicitPattern)) {
    anchors.add(decodeUrlComponent(match[1]).toLowerCase());
  }
  return anchors;
}

/**
 * Add a diagnostic once by stable code, path, and source tuple.
 * @param {Array<object>} diagnostics mutable diagnostics.
 * @param {Set<string>} keys existing diagnostic keys.
 * @param {object} diagnostic diagnostic to append.
 * @returns {void}
 */
function addDiagnostic(diagnostics, keys, diagnostic) {
  const key = [
    diagnostic.code,
    diagnostic.path ?? "",
    diagnostic.source ?? "",
  ].join("\0");
  if (keys.has(key)) return;
  keys.add(key);
  diagnostics.push(diagnostic);
}

/**
 * Validate a pure repository documentation snapshot.
 * @param {{
 *   version: string,
 *   manifest: object|null,
 *   knowledgeMap: object|null,
 *   status: string,
 *   releaseIndex: string,
 *   existingPaths: string[],
 *   texts: Record<string, string>
 * }} snapshot repository documentation state.
 * @returns {Array<{code: string, path?: string, source?: string, message: string}>}
 * diagnostics with stable machine-readable codes.
 */
export function validateDocumentationHealth(snapshot) {
  const diagnostics = [];
  const keys = new Set();
  const existingPaths = new Set(snapshot.existingPaths ?? []);
  const manifest = snapshot.manifest;
  const knowledgeMap = snapshot.knowledgeMap;
  const manifestPath = "doc/BlissHack/releases/manifest.json";
  const knowledgeMapPath = "doc/BlissHack/knowledge-map.json";

  if (!manifest) {
    addDiagnostic(diagnostics, keys, {
      code: "MANIFEST_REQUIRED",
      path: manifestPath,
      message: "Release manifest is missing.",
    });
  } else {
    if (manifest.schemaVersion !== 1) {
      addDiagnostic(diagnostics, keys, {
        code: "MANIFEST_SCHEMA_UNSUPPORTED",
        path: manifestPath,
        message:
          `Unsupported release manifest schema: ${manifest.schemaVersion}.`,
      });
    }
    if (manifest.currentVersion !== snapshot.version) {
      addDiagnostic(diagnostics, keys, {
        code: "MANIFEST_VERSION_MISMATCH",
        path: manifestPath,
        message:
          `Manifest currentVersion ${manifest.currentVersion} does not match `
          + `VERSION ${snapshot.version}.`,
      });
    }
    const releases = Array.isArray(manifest.releases)
      ? manifest.releases
      : [];
    if (!Array.isArray(manifest.releases)) {
      addDiagnostic(diagnostics, keys, {
        code: "MANIFEST_RELEASES_INVALID",
        path: manifestPath,
        message: "Release manifest releases must be an array.",
      });
    }
    const versions = new Set();
    for (const release of releases) {
      if (!release || typeof release !== "object") {
        addDiagnostic(diagnostics, keys, {
          code: "MANIFEST_RELEASE_INVALID",
          path: manifestPath,
          message: "Every release manifest entry must be an object.",
        });
        continue;
      }
      if (typeof release.version !== "string" || release.version === "") {
        addDiagnostic(diagnostics, keys, {
          code: "MANIFEST_VERSION_REQUIRED",
          path: manifestPath,
          message: "Every release manifest entry requires a version.",
        });
      } else if (versions.has(release.version)) {
        addDiagnostic(diagnostics, keys, {
          code: "MANIFEST_VERSION_DUPLICATE",
          path: manifestPath,
          message: `Duplicate release version: ${release.version}.`,
        });
      } else {
        versions.add(release.version);
      }
      if (typeof release.plan !== "string" || release.plan === "") {
        addDiagnostic(diagnostics, keys, {
          code: "MANIFEST_PLAN_REQUIRED",
          path: manifestPath,
          message: `Release ${release.version ?? "<unknown>"} requires a plan.`,
        });
      }
      if (
        release.acceptance !== null
        && release.acceptance !== undefined
        && typeof release.acceptance !== "string"
      ) {
        addDiagnostic(diagnostics, keys, {
          code: "MANIFEST_ACCEPTANCE_INVALID",
          path: manifestPath,
          message:
            `Release ${release.version ?? "<unknown>"} acceptance must be `
            + "a path or null.",
        });
      }
      if (!Array.isArray(release.artifacts)) {
        addDiagnostic(diagnostics, keys, {
          code: "MANIFEST_ARTIFACTS_INVALID",
          path: manifestPath,
          message:
            `Release ${release.version ?? "<unknown>"} artifacts must be `
            + "an array.",
        });
      } else if (
        release.artifacts.some((path) =>
          typeof path !== "string" || path === ""
        )
      ) {
        addDiagnostic(diagnostics, keys, {
          code: "MANIFEST_ARTIFACT_INVALID",
          path: manifestPath,
          message:
            `Release ${release.version ?? "<unknown>"} artifacts must `
            + "contain non-empty paths.",
        });
      }
      const declaredPaths = [
        typeof release.plan === "string" ? release.plan : null,
        typeof release.acceptance === "string" ? release.acceptance : null,
        ...(Array.isArray(release.artifacts)
          ? release.artifacts.filter((path) =>
            typeof path === "string" && path !== ""
          )
          : []),
      ].filter(Boolean);
      const releaseRoot = typeof release.version === "string"
        ? `doc/BlissHack/releases/${release.version}/`
        : "doc/BlissHack/releases/";
      for (const path of declaredPaths) {
        if (!path.startsWith(releaseRoot)) {
          addDiagnostic(diagnostics, keys, {
            code: "MANIFEST_PATH_OUTSIDE_ARCHIVE",
            path,
            message:
              `Release path must remain under ${releaseRoot}: ${path}`,
          });
        }
        if (!existingPaths.has(path)) {
          addDiagnostic(diagnostics, keys, {
            code: "MANIFEST_PATH_MISSING",
            path,
            message: `Release manifest path does not exist: ${path}`,
          });
        }
      }
    }
    if (Array.isArray(manifest.releases)) {
      try {
        const expectedStatus = generateCurrentStatus({
          version: snapshot.version,
          manifest,
        });
        if (snapshot.status !== expectedStatus) {
          addDiagnostic(diagnostics, keys, {
            code: "STATUS_OUTDATED",
            path: "doc/BlissHack/current/status.md",
            message: "Generated current status is missing or outdated.",
          });
        }
        const expectedReleaseIndex = generateReleaseIndex(manifest);
        if (snapshot.releaseIndex !== expectedReleaseIndex) {
          addDiagnostic(diagnostics, keys, {
            code: "RELEASE_INDEX_OUTDATED",
            path: "doc/BlissHack/releases/index.md",
            message: "Generated release index is missing or outdated.",
          });
        }
      } catch (error) {
        addDiagnostic(diagnostics, keys, {
          code: "CURRENT_RELEASE_MISSING",
          path: manifestPath,
          message: error.message,
        });
      }
    }
  }

  if (!knowledgeMap) {
    addDiagnostic(diagnostics, keys, {
      code: "KNOWLEDGE_MAP_REQUIRED",
      path: knowledgeMapPath,
      message: "Knowledge map is missing.",
    });
  } else if (knowledgeMap.schemaVersion !== 1) {
    addDiagnostic(diagnostics, keys, {
      code: "KNOWLEDGE_SCHEMA_UNSUPPORTED",
      path: knowledgeMapPath,
      message:
        `Unsupported knowledge map schema: ${knowledgeMap.schemaVersion}.`,
    });
  }

  const activeEntries = Array.isArray(knowledgeMap?.active)
    ? knowledgeMap.active
    : [];
  const active = new Set(activeEntries);
  if (knowledgeMap && !Array.isArray(knowledgeMap.active)) {
    addDiagnostic(diagnostics, keys, {
      code: "KNOWLEDGE_ACTIVE_INVALID",
      path: knowledgeMapPath,
      message: "Knowledge map active entries must be an array.",
    });
  }
  const activeCounts = new Map();
  for (const path of activeEntries) {
    const count = (activeCounts.get(path) ?? 0) + 1;
    activeCounts.set(path, count);
    if (count === 2) {
      addDiagnostic(diagnostics, keys, {
        code: "KNOWLEDGE_ACTIVE_DUPLICATE",
        path,
        message: `Duplicate active knowledge entry: ${path}`,
      });
    }
  }
  const decisionEntries = [...existingPaths].filter((path) =>
    /^doc\/BlissHack\/decisions\/[^/]+\.md$/.test(path)
  );
  for (const path of [...requiredActiveEntries, ...decisionEntries]) {
    if (!active.has(path)) {
      addDiagnostic(diagnostics, keys, {
        code: "KNOWLEDGE_ENTRY_REQUIRED",
        path,
        message: `Required active knowledge entry is not registered: ${path}`,
      });
    }
  }
  for (const path of active) {
    if (!existingPaths.has(path)) {
      addDiagnostic(diagnostics, keys, {
        code: "KNOWLEDGE_ENTRY_MISSING",
        path,
        message: `Registered active knowledge entry does not exist: ${path}`,
      });
    }
  }

  const archiveRoot = knowledgeMap?.archiveRoot;
  if (typeof archiveRoot !== "string" || archiveRoot === "") {
    addDiagnostic(diagnostics, keys, {
      code: "KNOWLEDGE_ARCHIVE_ROOT_REQUIRED",
      path: knowledgeMapPath,
      message: "Knowledge map requires a non-empty archiveRoot.",
    });
  } else if (!existingPaths.has(archiveRoot)) {
    addDiagnostic(diagnostics, keys, {
      code: "KNOWLEDGE_ARCHIVE_ROOT_MISSING",
      path: archiveRoot,
      message: `Knowledge archive root does not exist: ${archiveRoot}`,
    });
  }
  if (
    typeof archiveRoot === "string"
    && archiveRoot !== ""
    && archiveRoot !== "doc/BlissHack/releases"
  ) {
    addDiagnostic(diagnostics, keys, {
      code: "KNOWLEDGE_ARCHIVE_ROOT_MISMATCH",
      path: archiveRoot,
      message: "Knowledge archive root must be doc/BlissHack/releases.",
    });
  }

  const generated = new Set(
    Array.isArray(knowledgeMap?.generated) ? knowledgeMap.generated : [],
  );
  for (const path of requiredGeneratedEntries) {
    if (!generated.has(path)) {
      addDiagnostic(diagnostics, keys, {
        code: "KNOWLEDGE_GENERATED_REQUIRED",
        path,
        message: `Required generated entry is not registered: ${path}`,
      });
    }
  }
  for (const path of generated) {
    if (!existingPaths.has(path)) {
      addDiagnostic(diagnostics, keys, {
        code: "KNOWLEDGE_GENERATED_MISSING",
        path,
        message: `Generated knowledge entry does not exist: ${path}`,
      });
    }
  }

  for (const [name, expectedPath] of Object.entries(requiredEntrypoints)) {
    const path = knowledgeMap?.entrypoints?.[name];
    if (path !== expectedPath) {
      if (typeof path === "string" && !existingPaths.has(path)) {
        addDiagnostic(diagnostics, keys, {
          code: "KNOWLEDGE_ENTRYPOINT_MISSING",
          path,
          message: `Knowledge entrypoint ${name} does not exist: ${path}`,
        });
      } else {
        addDiagnostic(diagnostics, keys, {
          code: "KNOWLEDGE_ENTRYPOINT_MISMATCH",
          path: expectedPath,
          message:
            `Knowledge entrypoint ${name} must point to ${expectedPath}.`,
        });
      }
    } else if (!existingPaths.has(path)) {
      addDiagnostic(diagnostics, keys, {
        code: "KNOWLEDGE_ENTRYPOINT_MISSING",
        path,
        message: `Knowledge entrypoint ${name} does not exist: ${path}`,
      });
    }
  }

  for (const [path, source] of Object.entries(snapshot.texts ?? {})) {
    if (!isMaintainedPath(path)) continue;
    if (legacyPlansPattern.test(source)) {
      addDiagnostic(diagnostics, keys, {
        code: "LEGACY_PLAN_REFERENCE",
        path,
        message: `Legacy documentation path remains in ${path}.`,
      });
    }
    if (!path.toLowerCase().endsWith(".md")) continue;
    const linkData = markdownLinkData(source);
    for (const label of linkData.undefinedReferences) {
      addDiagnostic(diagnostics, keys, {
        code: "MARKDOWN_REFERENCE_UNDEFINED",
        path: label,
        source: path,
        message: `Undefined Markdown reference ${label} in ${path}.`,
      });
    }
    for (const target of linkData.targets) {
      const resolvedTarget = resolveMarkdownTarget(path, target);
      if (!resolvedTarget) continue;
      if (!existingPaths.has(resolvedTarget.path)) {
        addDiagnostic(diagnostics, keys, {
          code: "MARKDOWN_LINK_MISSING",
          path: resolvedTarget.path,
          source: path,
          message:
            `Missing Markdown link target ${resolvedTarget.path} from ${path}.`,
        });
        continue;
      }
      if (
        resolvedTarget.fragment
        && !/^l\d+(?:-l\d+)?$/i.test(resolvedTarget.fragment)
        && snapshot.texts?.[resolvedTarget.path] !== undefined
        && !markdownAnchors(snapshot.texts[resolvedTarget.path]).has(
          resolvedTarget.fragment,
        )
      ) {
        const anchoredPath =
          `${resolvedTarget.path}#${resolvedTarget.fragment}`;
        addDiagnostic(diagnostics, keys, {
          code: "MARKDOWN_ANCHOR_MISSING",
          path: anchoredPath,
          source: path,
          message: `Missing Markdown anchor ${anchoredPath} from ${path}.`,
        });
      }
    }
  }

  return diagnostics.sort((left, right) =>
    `${left.code}\0${left.path ?? ""}\0${left.source ?? ""}`.localeCompare(
      `${right.code}\0${right.path ?? ""}\0${right.source ?? ""}`,
    )
  );
}

/**
 * Return every parent directory represented by repository file paths.
 * @param {string[]} paths repository-relative file paths.
 * @returns {string[]} files and parent directories without duplicates.
 */
function withParentDirectories(paths) {
  const entries = new Set(paths);
  for (const path of paths) {
    let parent = normalizePath(dirname(path));
    while (parent !== ".") {
      entries.add(parent);
      parent = normalizePath(dirname(parent));
    }
  }
  return [...entries].sort();
}

/**
 * Read a UTF-8 file or return an empty string when it does not exist.
 * @param {string} path absolute path.
 * @returns {Promise<string>} file contents or an empty string.
 */
async function readOptionalFile(path) {
  try {
    return await readFile(path, "utf8");
  } catch (error) {
    if (error?.code === "ENOENT") return "";
    throw error;
  }
}

/**
 * Read a JSON file or return null when it does not exist.
 * @param {string} path absolute JSON path.
 * @returns {Promise<object|null>} parsed JSON value.
 */
async function readOptionalJson(path) {
  const source = await readOptionalFile(path);
  return source === "" ? null : JSON.parse(source);
}

/**
 * Build a validation snapshot from the current Git working tree.
 * @param {string} repositoryRoot absolute repository root.
 * @returns {Promise<object>} pure validation snapshot.
 */
async function createRepositorySnapshot(repositoryRoot) {
  const { stdout } = await execFileAsync(
    "git",
    ["ls-files", "--cached", "--others", "--exclude-standard", "-z"],
    {
      cwd: repositoryRoot,
      encoding: "buffer",
      maxBuffer: 16 * 1024 * 1024,
    },
  );
  const paths = stdout
    .toString("utf8")
    .split("\0")
    .filter(Boolean)
    .map(normalizePath)
    .sort();
  const textPaths = paths.filter((path) =>
    isMaintainedPath(path) && maintenanceTextPattern.test(path)
  );
  const textEntries = await Promise.all(textPaths.map(async (path) => [
    path,
    await readFile(join(repositoryRoot, path), "utf8"),
  ]));
  const [
    version,
    manifest,
    knowledgeMap,
    status,
    releaseIndex,
  ] = await Promise.all([
    readOptionalFile(join(repositoryRoot, "VERSION")),
    readOptionalJson(
      join(repositoryRoot, "doc/BlissHack/releases/manifest.json"),
    ),
    readOptionalJson(
      join(repositoryRoot, "doc/BlissHack/knowledge-map.json"),
    ),
    readOptionalFile(
      join(repositoryRoot, "doc/BlissHack/current/status.md"),
    ),
    readOptionalFile(
      join(repositoryRoot, "doc/BlissHack/releases/index.md"),
    ),
  ]);
  return {
    version: version.trim(),
    manifest,
    knowledgeMap,
    status,
    releaseIndex,
    existingPaths: withParentDirectories(paths),
    texts: Object.fromEntries(textEntries),
  };
}

/**
 * Write generated documentation files from the current manifests.
 * @param {string} repositoryRoot absolute repository root.
 * @param {object} snapshot repository documentation state.
 * @returns {Promise<void>}
 */
async function writeGeneratedDocumentation(repositoryRoot, snapshot) {
  const outputs = new Map([
    [
      "doc/BlissHack/current/status.md",
      generateCurrentStatus({
        version: snapshot.version,
        manifest: snapshot.manifest,
      }),
    ],
    [
      "doc/BlissHack/releases/index.md",
      generateReleaseIndex(snapshot.manifest),
    ],
  ]);
  for (const [path, contents] of outputs) {
    const absolutePath = join(repositoryRoot, path);
    await mkdir(dirname(absolutePath), { recursive: true });
    await writeFile(absolutePath, contents, "utf8");
  }
}

/**
 * Run generation or validation from the command line.
 * @returns {Promise<void>}
 */
async function main() {
  const repositoryRoot = resolve(
    dirname(fileURLToPath(import.meta.url)),
    "../..",
  );
  let snapshot = await createRepositorySnapshot(repositoryRoot);
  if (process.argv.includes("--write")) {
    await writeGeneratedDocumentation(repositoryRoot, snapshot);
    snapshot = await createRepositorySnapshot(repositoryRoot);
  }
  const diagnostics = validateDocumentationHealth(snapshot);
  if (diagnostics.length > 0) {
    for (const diagnostic of diagnostics) {
      console.error(
        `${diagnostic.code}: ${diagnostic.message}`
        + (diagnostic.source ? ` [source: ${diagnostic.source}]` : ""),
      );
    }
    process.exitCode = 1;
    return;
  }
  console.log("Documentation health checks passed.");
}

const invokedPath = process.argv[1]
  ? pathToFileURL(resolve(process.argv[1])).href
  : "";
if (invokedPath === import.meta.url) {
  await main();
}
